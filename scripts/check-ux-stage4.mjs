import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { readThroughSelection } from '../src/progress/read-through.ts';
import { summarizeReadingPlan } from '../src/views/home-model.ts';

const text = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const index = JSON.parse(text('src/data/generated-index.json'));
const fields = Object.fromEntries(index.itemIndexFields.map((name, i) => [name, i]));
const readings = index.itemIndex.map(row => Object.fromEntries(['id', 'type', 'historicalNumber', 'weight'].map(key => [key, row[fields[key]]])));
let checks = 0;
const ok = (condition, message) => { assert.ok(condition, message); console.log(`PASS ${++checks}: ${message}`); };

const current = new Map([[2, 'Sim'], [3, 'Pulei']]);
const status = id => current.get(id) || 'Não';
const preview = readThroughSelection(5, readings, status);
ok(preview.pending.length === 3 && preview.alreadyRead === 1 && preview.skipped === 1, 'prévia separa pendentes, lidas e puladas');
ok(preview.pending.every(item => item.type === 'Principal'), 'nenhuma leitura extra ou contextual é marcada');
ok(!preview.pending.some(item => item.id === 1) && readThroughSelection(1, readings, status).total === 1, 'Amazing Fantasy #15 fora da linha histórica permanece intocada');
ok(readThroughSelection(0, readings, status).total === 0 && readThroughSelection(1001, readings, status).total === 0, 'números históricos inválidos não selecionam itens');
ok(readThroughSelection(1000, readings, status).pending.every(item => item.type === 'Principal'), 'seleção até #1000 limita-se à linha principal');
const summary = summarizeReadingPlan(readings.slice(0, 6), status);
ok(summary.read === 1 && summary.skipped === 1 && summary.pending === 4 && summary.next?.id === 1, 'progresso mantém Pulei separado de Sim e respeita readingOrder');
ok(summarizeReadingPlan([readings[1], readings[2]], id => id === 2 ? 'Sim' : 'Pulei').next === undefined, 'plano sem pendências não confunde pulada com lida');
ok(summarizeReadingPlan([], status).total === 0, 'plano vazio não inventa progresso');
const home = text('src/views/HomeView.tsx');
const settings = text('src/views/MoreView.tsx');
const runtime = text('src/runtime/controller.ts');
ok(home.includes('readThroughSelection') && home.includes('Revisar e atualizar') && home.includes('home-read-through-preview'), 'Home oferece prévia e confirmação');
ok(!settings.includes('account-read-through') && !settings.includes('applyReadThrough'), 'Configurações não duplica Já li até');
ok(runtime.includes('if (!confirmed) return 0') && runtime.includes('preview.pending.filter(item => statusOf(item.id) === \'Não\')'), 'cancelamento e confirmação revalidam mudanças concorrentes');
ok(runtime.includes('readingPreferences.set({ readThrough: previousBaseline })'), 'desfazer também restaura preferência anterior');
ok(home.includes('summary.skipped') && home.includes('Alterar nas Configurações') && home.includes('Revisar sincronização'), 'fluxo inicial mostra puladas, plano e recuperação de sync');
ok(text('tests/e2e/home-stage4.spec.ts').includes('confirmar e desfazer') && text('tests/e2e/home-stage4.spec.ts').includes('width: 360'), 'cenários de navegador adicionados');
console.log(`Etapa 4: ${checks} verificações locais passaram.`);
