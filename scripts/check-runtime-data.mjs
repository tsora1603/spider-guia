import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { ROOT } from './lib/data-utils.mjs';

import { validateEditorialLinks } from '../data/link-model.mjs';
const context = { window: {}, console, URL };
context.globalThis = context;
vm.createContext(context);
const dataSource = await fs.readFile(path.join(ROOT, 'data.js'), 'utf8');
const validatorSource = await fs.readFile(path.join(ROOT, 'public/validator.js'), 'utf8');
vm.runInContext(`${dataSource}\nglobalThis.__SPIDER_DATA__ = DATA;`, context, { filename: 'data.js' });
vm.runInContext(validatorSource, context, { filename: 'validator.js' });
const data = context.__SPIDER_DATA__;
const links = data.editorial.links;
const result = context.window.SpiderValidator.validate(data, links);
result.errors.push(...validateEditorialLinks(links, {knownItemIds:new Set(data.items.map(row=>row[0])), extras:data.editorial.extras}));
result.ok = result.errors.length === 0;
console.log(JSON.stringify(result, null, 2));
if (!result.ok) process.exit(1);
